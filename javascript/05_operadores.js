console.log("operadores Aritméticos ");
let a = 10;
let b = 5;

console.log("Suma:", a + b);
console.log("Resta:", a - b);
console.log("Multiplicación:", a * b);
console.log("División:", a / b);
console.log("Módulo:", a % b);

console.log("operadores de comparación");
console.log("Igualdad:", a == b);
console.log("Desigualdad:", a != b);
console.log("Mayor que:", a > b);
console.log("Menor que:", a < b);
console.log("Mayor o igual que:", a >= b);
console.log("Menor o igual que:", a <= b);

console.log("operadores lógicos");
let x = true;
let y = false;

console.log("AND (&&):", x && y);
console.log("OR (||):", x || y);
console.log("NOT (!):", !x);
console.log("NOT (!):", !y);

console.log("operadores de asignación");
let c = 10;
console.log("Valor inicial de c:", c);
c += 5; // c = c + 5
console.log("Después de c += 5:", c);
c -= 3; // c = c - 3
console.log("Después de c -= 3:", c);
c *= 2; // c = c * 2
console.log("Después de c *= 2:", c);
c /= 4; // c = c / 4
console.log("Después de c /= 4:", c);
c %= 3; // c = c % 3
console.log("Después de c %= 3:", c);

console.log("operadores de incremento y decremento");
let d = 5;
console.log("Valor inicial de d:", d);
d++; // Incremento
console.log("Después de d++:", d);
d--; // Decremento
console.log("Después de d--:", d);


